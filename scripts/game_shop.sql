DROP DATABASE IF EXISTS game_shop;
CREATE DATABASE game_shop;
USE game_shop;

CREATE TABLE platforms (
  platform_id   INT PRIMARY KEY,
  name          VARCHAR(40) NOT NULL,
  manufacturer  VARCHAR(40) NOT NULL
);

CREATE TABLE games (
  game_id       INT PRIMARY KEY,
  title         VARCHAR(80) NOT NULL,
  platform_id   INT NOT NULL,
  genre         VARCHAR(20) NOT NULL,
  esrb_rating   VARCHAR(5)  NOT NULL,
  price         DECIMAL(6,2) NOT NULL,
  stock_qty     INT NOT NULL DEFAULT 0,
  release_date  DATE NULL,             -- some unknown: try IS NULL
  FOREIGN KEY (platform_id) REFERENCES platforms(platform_id)
);

CREATE TABLE customers (
  customer_id   INT PRIMARY KEY,
  first_name    VARCHAR(30) NOT NULL,
  last_name     VARCHAR(30) NOT NULL,
  email         VARCHAR(80) NOT NULL UNIQUE,
  phone         VARCHAR(15) NULL,      -- about 20% missing
  city          VARCHAR(40) NOT NULL,
  province      CHAR(2) NOT NULL,
  joined_date   DATE NOT NULL
);

CREATE TABLE orders (
  order_id      INT PRIMARY KEY,
  customer_id   INT NOT NULL,
  order_date    DATE NOT NULL,
  status        VARCHAR(12) NOT NULL,  -- Pending, Shipped, Delivered, Cancelled
  shipped_date  DATE NULL,
  FOREIGN KEY (customer_id) REFERENCES customers(customer_id)
);

CREATE TABLE order_items (
  order_item_id INT PRIMARY KEY,
  order_id      INT NOT NULL,
  game_id       INT NOT NULL,
  quantity      INT NOT NULL,
  unit_price    DECIMAL(6,2) NOT NULL,
  FOREIGN KEY (order_id) REFERENCES orders(order_id),
  FOREIGN KEY (game_id)  REFERENCES games(game_id)
);

